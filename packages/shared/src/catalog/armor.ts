import { C } from '../palette';
import type { ArmorSet, ArmorSlot } from '../equipment';

/**
 * Armour sets beyond the five that shipped first. Each is made of one material (a metal's plate, leather, or cloth) so
 * a player reads the ladder at a glance: padded and linen cloth, fur and studded hide, bronze and chain, steel, then
 * the rare metals and each kingdom's own. `look: -1` means the set has no worn-set sprite: it keeps the outfit you chose
 * and only changes your numbers (the five original sets still redraw you).
 */
export type SetKind = 'metal' | 'leather' | 'cloth';
export interface CatalogSet extends ArmorSet {
  kind: SetKind;
  /** realm that taught the pattern (recipes need standing there) */
  realm?: string;
}

const P = (a: string, b: string, c: string, d: string): Record<ArmorSlot, string> => ({
  head: a,
  chest: b,
  legs: c,
  feet: d,
});

const s = (
  id: string,
  name: string,
  kind: SetKind,
  mat: string,
  level: number,
  colors: [number, number],
  piece: ArmorSet['piece'],
  two: ArmorSet['two'],
  four: ArmorSet['four'],
  blurb: string,
  pieces: Record<ArmorSlot, string>,
  realm?: string,
): CatalogSet => ({
  id,
  name,
  kind,
  mat,
  level,
  colors,
  look: -1,
  piece,
  two,
  four,
  blurb,
  pieces,
  ...(realm ? { realm } : {}),
});

