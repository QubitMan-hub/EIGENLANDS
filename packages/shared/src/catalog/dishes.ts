import { COL as C, item, rec } from './kit';
import type { BuffKind } from '../items';
import type { Rarity, StationId } from '../crafting';
import type { Glyph } from '../items';

/**
 * Cooking. Dishes are data rows: what goes in, how heavy a meal it is (snack to banquet), what it does (its profile) and
 * whose kitchen it comes from. The numbers (health, hunger, buff strength and length) follow from weight, profile and the
 * level it takes to cook, so a hundred dishes stay balanced and every one does something a player can feel.
 *
 * Profiles: hearty = more health, spicy = attack, fresh = speed, sweet = regeneration, savory = damage reduction,
 * rich = stamina, lucky = luck, herbal = ingredient saving, cool/warm = temperature, plain = just food.
 */
type Prof = 'hearty' | 'spicy' | 'fresh' | 'sweet' | 'savory' | 'rich' | 'lucky' | 'herbal' | 'cool' | 'warm' | 'plain';
type Wt = 1 | 2 | 3 | 4 | 5;
type Key = 'r' | 'R' | 'o' | 'y' | 'g' | 'G' | 'w' | 'p' | 'b' | 'B' | 'k' | 'v' | 'c' | 't' | 's';
const K: Record<Key, number> = {
  r: C.r4,
  R: C.r3,
  o: C.e5,
  y: C.e7,
  g: C.g4,
  G: C.g3,
  w: C.white,
  p: C.pale,
  b: C.e4,
  B: C.e2,
  k: C.night,
  v: C.q4,
  c: C.w4,
  t: C.w6,
  s: C.steel,
};

const HEAL = [8, 20, 40, 65, 95];
const NOUR = [8, 18, 32, 46, 60];
const round1 = (n: number): number => Math.round(n * 10) / 10;
function effect(prof: Prof, wt: Wt, lvl: number): { kind: BuffKind; secs: number; power: number } | null {
  switch (prof) {
    case 'hearty':
      return { kind: 'vigor', secs: 300, power: Math.round(6 + lvl * 2.2 + wt * 3) };
    case 'spicy':
      return { kind: 'fury', secs: 200, power: Math.round(1 + lvl * 0.45 + wt * 0.8) };
    case 'fresh':
      return { kind: 'swift', secs: 240, power: round1(0.4 + lvl * 0.1 + wt * 0.15) };
    case 'sweet':
      return { kind: 'regen', secs: 120, power: round1(0.8 + lvl * 0.08 + wt * 0.2) };
    case 'savory':
      return { kind: 'bulwark', secs: 240, power: round1(Math.min(0.3, 0.03 + lvl * 0.006 + wt * 0.01) * 100) / 100 };
    case 'rich':
      return { kind: 'steady', secs: 360, power: Math.round(6 + lvl * 1.3 + wt * 2) };
    case 'lucky':
      return { kind: 'fortune', secs: 300, power: round1(0.4 + lvl * 0.11 + wt * 0.12) };
    case 'herbal':
      return { kind: 'focus', secs: 300, power: Math.round(Math.min(18, 2 + lvl * 0.5 + wt * 0.7)) };
    case 'cool':
      return { kind: 'coolness', secs: 420, power: round1(Math.min(0.9, 0.5 + wt * 0.08)) };
    case 'warm':
      return { kind: 'warmth', secs: 420, power: round1(Math.min(0.9, 0.5 + wt * 0.08)) };
    default:
      return null;
  }
}

type Row = [
  id: string,
  name: string,
  st: 'pot' | 'oven' | 'brew',
  prof: Prof,
  wt: Wt,
  lvl: number,
  inputs: Array<[string, number]>,
  desc: string,
  g: Glyph,
  cols: `${Key}${Key}`,
];

export function dishes(rows: Row[], realm?: string): void {
  for (const [id, name, st, prof, wt, lvl, inputs, desc, g, cols] of rows) {
    const buff = effect(prof, wt, lvl);
    const rarity: Rarity = lvl < 6 ? 0 : lvl < 12 ? 1 : lvl < 20 ? 2 : 3;
    const drink = st === 'brew' || DRINKS.has(id);
    item(id, name, drink ? 'drink' : 'dish', {
      v: 10 + wt * 14 + lvl * 5 + inputs.length * 3,
      g,
      a: K[cols[0] as Key],
      b: K[cols[1] as Key],
      d: desc,
      heal: HEAL[wt - 1]!,
      nourishment: NOUR[wt - 1]!,
      ...(buff ? { buff } : {}),
      rarity,
      ...(realm ? { realm } : {}),
    });
    const station: StationId = st === 'pot' ? 'cooking_pot' : st === 'oven' ? 'oven' : 'brewery';
    rec(station, inputs, [id, 1], {
      lvl,
      disc: st === 'brew' ? 'brewing' : 'cooking',
      xp: 6 + lvl * 2,
      learn: realm
        ? `realm:${realm}`
        : DISCOVER.has(id) && inputs.length <= 4
          ? 'discover'
          : lvl <= 2
            ? 'start'
            : 'level',
      hint: desc,
      stage: 3,
      cat: drink ? 'drink' : 'dish',
      ...(realm ? { realm } : {}),
    });
  }
}

