/**
 * Crops beyond the first thirteen: grains, vegetables, orchard and vine fruit, spice and tea plants, fibre and oil crops.
 * Pure data. `crops.ts` adds them to CROPS (growth, seasons, art hints) and farm.ts makes their seed and crop items.
 * A seed is sold in the kingdoms that grow the plant, so travelling for a recipe's ingredients is part of the game.
 */
export interface CropRow {
  def: CropDef;
  /** seed price; the harvest sells for about 3x */
  seed: number;
  crop: number;
  glyph: 'root' | 'leaf' | 'fruit' | 'berry' | 'wheat' | 'pepper' | 'onion' | 'flower' | 'mushroom';
  /** shops that sell the seed: 'general' everywhere, or the kingdoms that grow it */
  sold: Array<'general' | 'aurelion' | 'sylvaris' | 'khardum' | 'raijin' | 'thalassara' | 'nethrakar'>;
  blurb: string;
  /** hunger restored when eaten raw */
  raw?: number;
  /** a tree or vine that keeps bearing */
  orchard?: boolean;
}

