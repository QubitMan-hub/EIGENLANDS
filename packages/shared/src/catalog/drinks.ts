import { dishes, DRINKS } from './dishes';

/**
 * Teas, juices and coffees from the pot; beer, wine, mead and spirits from the brewing barrel. Each drink is a small
 * boost with its own flavour; the heavier spirits are made from the lighter brews, so a brewer climbs a ladder.
 */
const pot = (rows: Parameters<typeof dishes>[0], realm?: string): void => {
  for (const r of rows) DRINKS.add(r[0]);
  dishes(rows, realm);
};

