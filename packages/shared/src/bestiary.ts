export type BestiaryKey = keyof typeof CREATURE_BLUEPRINTS;
export const BESTIARY_KEYS = Object.keys(CREATURE_BLUEPRINTS) as BestiaryKey[];
export const bestiaryKind = (id: BestiaryKey): number => 74 + BESTIARY_KEYS.indexOf(id);
const TROPHIES: Partial<Record<BestiaryKey, string>> = {
  primordial_dragon: 'first_flame_ember',
  world_serpent: 'remembering_pearl',
  sealed_entity: 'unwritten_page',
  forgotten_titan: 'morrowforge_core',
  realm_guardian: 'sixfold_crown',
};
export const BESTIARY_DEFS = Object.fromEntries(
  BESTIARY_KEYS.map((id) => {
    const b: CreatureBlueprint = CREATURE_BLUEPRINTS[id],
      ancient = b.category === 'ancient',
      mythical = ancient || b.category === 'mythical';
    const trophy = TROPHIES[id];
    return [
      id,
      {
        kind: bestiaryKind(id),
        name: b.name,
        hp: b.hp,
        damage: b.damage,
        speed: b.speed,
        radius: b.radius ?? 0.42,
        sight: mythical ? 15 : 11,
        windup: b.windup ?? 0.7,
        strikeRange: b.range ?? 1.6,
        xp: ancient ? 1200 : mythical ? 80 : b.category === 'passive' ? 4 : 18,
        ai: b.ai,
        passive: b.category === 'passive',
        neutral: b.neutral,
        sea: b.sea,
        armor: b.armor,
        trait: b.trait,
        territory: b.territory,
        predator: b.predator,
        mythical,
        poise: ancient ? 160 : mythical ? 65 : 25,
        resist: ancient ? 0.12 : mythical ? 0.45 : 1,
        cooldown: b.cooldown ?? (mythical ? 2.2 : 1.5),
        budget: b.budget ?? 1,
        boss: ancient,
        drops:
          b.category === 'passive'
            ? [{ item: id === 'river_fish' ? 'carp' : 'fiber', min: 1, max: 1, chance: 0.6 }]
            : [
                { item: 'qubit_crystal', min: ancient ? 8 : 1, max: ancient ? 12 : 2, chance: mythical ? 1 : 0.12 },
                { item: 'wild_essence', min: ancient ? 6 : 1, max: ancient ? 10 : 2, chance: mythical ? 1 : 0.25 },
                ...(trophy
                  ? [
                      { item: trophy, min: 1, max: 1, chance: 1 },
                      { item: 'heart_crystal', min: 1, max: 1, chance: 1 },
                      { item: 'gold_ingot', min: 3, max: 6, chance: 1 },
                    ]
                  : []),
              ],
      } satisfies EnemyDef,
    ];
  }),
) as Record<BestiaryKey, EnemyDef>;
export function rareSpawnEntries(level: number, night: boolean, biome: Biome): Array<{ kind: BestiaryKey; w: number }> {
  return BESTIARY_KEYS.filter((id) => {
    const b: CreatureBlueprint = CREATURE_BLUEPRINTS[id];
    return (
      b.weight > 0 && level >= b.min && b.habitat.includes(biome) && (!['undead', 'rogue_mage'].includes(id) || night)
    );
  }).map((kind) => ({ kind, w: CREATURE_BLUEPRINTS[kind].weight }));
}
