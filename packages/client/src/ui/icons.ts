/** SVG markup for a named pixel icon, sized in CSS px. */
export function iconSvg(name: string, px = 18, cls = ''): string {
  const g = I[name] ?? I.hex!;
  const h = g.length,
    w = g[0]!.length;
  let r = '';
  g.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === '#') r += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
      else if (c === 'o') r += `<rect class="acc" x="${x}" y="${y}" width="1" height="1"/>`;
      else if (c === 'x') r += `<rect class="dk" x="${x}" y="${y}" width="1" height="1"/>`;
    }
  });
  return `<svg class="pix ${cls}" viewBox="0 0 ${w} ${h}" width="${px}" height="${Math.round((px * h) / w)}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${r}</svg>`;
}

export function iconEl(name: string, px = 18, cls = ''): HTMLElement {
  const s = document.createElement('span');
  s.className = 'ic';
  s.innerHTML = iconSvg(name, px, cls);
  return s;
}
